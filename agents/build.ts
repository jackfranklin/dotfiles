/**
 * Generates Claude Code and Pi skills and subagents from agents/skills and
 * agents/subagents, then links each one into the directory its harness reads.
 * See agents/README.md.
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {
  BuildError,
  HARNESSES,
  insertHeader,
  parseSubagent,
  renderClaudeSubagent,
  renderPiSubagent,
  renderTemplate,
  validateSkillManifest,
  type Harness,
  type SubagentSource,
} from './transform.ts';

export interface InstallTargets {
  skills: string;
  agents: string;
}

export interface BuildOptions {
  sourceDir: string;
  distDir: string;
  targets: Record<Harness, InstallTargets>;
}

export interface BuildResult {
  skills: string[];
  subagents: string[];
  pruned: string[];
}

type Kind = keyof InstallTargets;
const KINDS: readonly Kind[] = ['skills', 'agents'];

interface OutputFile {
  content: string | Buffer;
  mode: number;
}

export function defaultOptions(): BuildOptions {
  const home = os.homedir();
  return {
    sourceDir: import.meta.dirname,
    distDir: path.join(import.meta.dirname, 'dist'),
    targets: {
      claude: {
        skills: path.join(home, '.claude', 'skills'),
        agents: path.join(home, '.claude', 'agents'),
      },
      pi: {
        skills: path.join(home, '.pi', 'agent', 'skills'),
        agents: path.join(home, '.pi', 'agent', 'agents'),
      },
    },
  };
}

function header(sourcePath: string): string {
  return `<!-- Generated by agents/build.ts from agents/${sourcePath}. Do not edit: change the source and run \`make agents\`. -->`;
}

function lstatOrUndefined(filePath: string): fs.Stats | undefined {
  try {
    return fs.lstatSync(filePath);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
    throw error;
  }
}

/** Lists a source directory, which may be missing but must not contain symlinks. */
function listDir(dir: string, label: string): fs.Dirent[] {
  const stats = lstatOrUndefined(dir);
  if (!stats) return [];
  if (!stats.isDirectory()) throw new BuildError(label, 'expected a directory');
  const entries = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((entry) => !entry.name.startsWith('.'))
    .sort((a, b) => (a.name < b.name ? -1 : 1));
  for (const entry of entries) {
    if (entry.isSymbolicLink()) {
      throw new BuildError(
        `${label}/${entry.name}`,
        'sources must not be symlinks',
      );
    }
  }
  return entries;
}

function listFiles(dir: string, label: string, prefix = ''): string[] {
  return listDir(dir, label).flatMap((entry) => {
    const relative = path.join(prefix, entry.name);
    return entry.isDirectory()
      ? listFiles(
          path.join(dir, entry.name),
          `${label}/${entry.name}`,
          relative,
        )
      : [relative];
  });
}

/** Renders every source into `<harness>/<kind>/...` paths without touching the filesystem. */
function renderAll(options: BuildOptions) {
  const outputs = new Map<string, OutputFile>();
  const skillsSource = path.join(options.sourceDir, 'skills');
  const subagentsSource = path.join(options.sourceDir, 'subagents');

  const skillNames: string[] = [];
  for (const entry of listDir(skillsSource, 'skills')) {
    const skillDir = path.join(skillsSource, entry.name);
    const label = `skills/${entry.name}`;
    if (!entry.isDirectory()) {
      throw new BuildError(label, 'expected a skill directory');
    }
    if (!lstatOrUndefined(path.join(skillDir, 'SKILL.md'))?.isFile()) {
      throw new BuildError(label, 'skill directory has no SKILL.md');
    }
    for (const file of listFiles(skillDir, label)) {
      const sourcePath = path.join(skillDir, file);
      const fileLabel = `${label}/${file}`;
      const { mode } = fs.statSync(sourcePath);
      if (file === 'SKILL.md') {
        validateSkillManifest(
          fs.readFileSync(sourcePath, 'utf8'),
          entry.name,
          fileLabel,
        );
      }
      for (const harness of HARNESSES) {
        const outputPath = path.join(harness, 'skills', entry.name, file);
        if (!file.endsWith('.md')) {
          outputs.set(outputPath, {
            content: fs.readFileSync(sourcePath),
            mode: mode & ~0o222,
          });
          continue;
        }
        const text = fs.readFileSync(sourcePath, 'utf8');
        const rendered = renderTemplate(
          text,
          harness,
          options.targets[harness].skills,
          fileLabel,
        );
        outputs.set(outputPath, {
          content:
            file === 'SKILL.md'
              ? insertHeader(rendered, header(fileLabel))
              : rendered,
          mode: 0o444,
        });
      }
    }
    skillNames.push(entry.name);
  }

  const subagents: SubagentSource[] = [];
  for (const entry of listDir(subagentsSource, 'subagents')) {
    const label = `subagents/${entry.name}`;
    if (!entry.name.endsWith('.md') || !entry.isFile()) {
      throw new BuildError(label, 'expected a .md subagent definition');
    }
    const text = fs.readFileSync(
      path.join(subagentsSource, entry.name),
      'utf8',
    );
    subagents.push(
      parseSubagent(text, path.basename(entry.name, '.md'), label),
    );
  }

  const subagentNames = subagents.map((agent) => agent.name);
  for (const agent of subagents) {
    const label = `subagents/${agent.name}.md`;
    for (const skill of agent.skills) {
      if (!skillNames.includes(skill))
        throw new BuildError(label, `unknown skill "${skill}"`);
    }
    for (const name of agent.piSubagentAgents ?? []) {
      if (!subagentNames.includes(name))
        throw new BuildError(label, `unknown subagent "${name}"`);
    }
    const generatedHeader = header(label);
    outputs.set(path.join('claude', 'agents', `${agent.name}.md`), {
      content: renderClaudeSubagent(
        agent,
        renderTemplate(
          agent.body,
          'claude',
          options.targets.claude.skills,
          label,
        ),
        generatedHeader,
      ),
      mode: 0o444,
    });
    outputs.set(path.join('pi', 'agents', `${agent.name}.md`), {
      content: renderPiSubagent(
        agent,
        renderTemplate(agent.body, 'pi', options.targets.pi.skills, label),
        generatedHeader,
        options.targets.pi.skills,
      ),
      mode: 0o444,
    });
  }

  const items: Record<Kind, string[]> = {
    skills: skillNames,
    agents: subagentNames.map((name) => `${name}.md`),
  };
  return { outputs, items, skillNames, subagentNames };
}

/**
 * A link is ours when it points into this build's output for its harness and
 * kind. Uses readlink rather than realpath so dangling links still resolve.
 */
function isOwnedLink(linkPath: string, ownedDir: string): boolean {
  if (!lstatOrUndefined(linkPath)?.isSymbolicLink()) return false;
  const target = path.resolve(
    path.dirname(linkPath),
    fs.readlinkSync(linkPath),
  );
  return target.startsWith(ownedDir + path.sep);
}

function preflight(
  options: BuildOptions,
  distDir: string,
  items: Record<Kind, string[]>,
): void {
  for (const harness of HARNESSES) {
    for (const kind of KINDS) {
      const targetDir = options.targets[harness][kind];
      const stats = lstatOrUndefined(targetDir);
      if (!stats) continue;
      if (stats.isSymbolicLink()) {
        throw new BuildError(
          targetDir,
          'is a symlink; replace it with a real directory (see agents/README.md → Migrating)',
        );
      }
      if (!stats.isDirectory())
        throw new BuildError(targetDir, 'is not a directory');

      const ownedDir = path.join(distDir, harness, kind);
      for (const name of items[kind]) {
        const linkPath = path.join(targetDir, name);
        const existing = lstatOrUndefined(linkPath);
        if (!existing || isOwnedLink(linkPath, ownedDir)) continue;
        const detail = existing.isSymbolicLink()
          ? `a symlink to ${fs.readlinkSync(linkPath)}`
          : 'a file or directory not managed by this build';
        throw new BuildError(
          linkPath,
          `already exists as ${detail}; remove it first`,
        );
      }
    }
  }
}

/** Writes all output to a temporary directory, then swaps it in place of `distDir`. */
function writeDist(distDir: string, outputs: Map<string, OutputFile>): void {
  const tmpDir = `${distDir}.tmp`;
  const oldDir = `${distDir}.old`;
  fs.rmSync(tmpDir, { recursive: true, force: true });
  fs.rmSync(oldDir, { recursive: true, force: true });
  for (const [relative, file] of outputs) {
    const filePath = path.join(tmpDir, relative);
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, file.content);
    fs.chmodSync(filePath, file.mode);
  }
  for (const harness of HARNESSES) {
    for (const kind of KINDS)
      fs.mkdirSync(path.join(tmpDir, harness, kind), { recursive: true });
  }
  const hadDist = fs.existsSync(distDir);
  if (hadDist) fs.renameSync(distDir, oldDir);
  try {
    fs.renameSync(tmpDir, distDir);
  } catch (error) {
    // Put the previous build back so existing links keep working.
    if (hadDist) fs.renameSync(oldDir, distDir);
    throw error;
  }
  fs.rmSync(oldDir, { recursive: true, force: true });
}

function linkAndPrune(
  options: BuildOptions,
  distDir: string,
  items: Record<Kind, string[]>,
): string[] {
  const pruned: string[] = [];
  for (const harness of HARNESSES) {
    for (const kind of KINDS) {
      const targetDir = options.targets[harness][kind];
      const ownedDir = path.join(distDir, harness, kind);
      fs.mkdirSync(targetDir, { recursive: true });

      for (const name of items[kind]) {
        const linkPath = path.join(targetDir, name);
        const expected = path.join(ownedDir, name);
        if (lstatOrUndefined(linkPath)) {
          if (fs.readlinkSync(linkPath) === expected) continue;
          fs.unlinkSync(linkPath);
        }
        fs.symlinkSync(expected, linkPath);
      }

      for (const entry of fs.readdirSync(targetDir)) {
        const linkPath = path.join(targetDir, entry);
        if (items[kind].includes(entry) || !isOwnedLink(linkPath, ownedDir))
          continue;
        fs.unlinkSync(linkPath);
        pruned.push(`${harness}/${kind}/${entry}`);
      }
    }
  }
  return pruned;
}

export function build(input: BuildOptions): BuildResult {
  // Resolving drops trailing slashes, which would make lstat follow a symlinked target.
  const options: BuildOptions = {
    sourceDir: path.resolve(input.sourceDir),
    distDir: path.resolve(input.distDir),
    targets: {
      claude: {
        skills: path.resolve(input.targets.claude.skills),
        agents: path.resolve(input.targets.claude.agents),
      },
      pi: {
        skills: path.resolve(input.targets.pi.skills),
        agents: path.resolve(input.targets.pi.agents),
      },
    },
  };
  const { distDir } = options;
  const { outputs, items, skillNames, subagentNames } = renderAll(options);
  preflight(options, distDir, items);
  writeDist(distDir, outputs);
  const pruned = linkAndPrune(options, distDir, items);
  return { skills: skillNames, subagents: subagentNames, pruned };
}

if (import.meta.main) {
  try {
    const result = build(defaultOptions());
    console.log(
      `Built ${result.skills.length} skills and ${result.subagents.length} subagents for ${HARNESSES.join(' and ')}.`,
    );
    for (const name of result.pruned) console.log(`Pruned ${name}`);
  } catch (error) {
    if (!(error instanceof BuildError)) throw error;
    console.error(error.message);
    process.exit(1);
  }
}
