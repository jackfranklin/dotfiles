import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');

async function readJson(path) {
  return JSON.parse(await readFile(resolve(root, path), 'utf8'));
}

const [corne, iris] = await Promise.all([
  readJson('keyboard-layouts/corne-v4.vil'),
  readJson('keyboard-layouts/iris_rev__7.layout.json'),
]);

const layouts = [
  {
    id: 'corne-v4',
    name: 'Corne v4',
    firmware: 'Vial / QMK',
    source: '../corne-v4.vil',
    sourceLabel: 'Vial backup',
    geometry: 'corne',
    layers: corne.layout,
  },
  {
    id: 'iris-rev7',
    name: iris.name,
    firmware: 'VIA / QMK',
    source: '../iris_rev__7.layout.json',
    sourceLabel: 'VIA backup',
    geometry: 'iris',
    layers: iris.layers,
  },
];

const output = `// Generated by scripts/build-keyboard-layouts.mjs; do not edit.\nwindow.KEYBOARD_LAYOUTS = ${JSON.stringify(
  layouts,
  null,
  2,
)};\n`;

await writeFile(
  resolve(root, 'keyboard-layouts/viewer/layout-data.js'),
  output,
);
